#!/usr/bin/env python3
"""
Make the Chumby icon fonts: a few Material Icons glyphs (Apache-2.0,
https://github.com/google/material-design-icons, font/MaterialIcons-
Regular.ttf) LVGL's built-in symbols don't have (a radio, a clock, a
globe, a sun, a podcast, skip back 10 s / ahead 30 s), as LVGL 9 fonts (lv_font_fmt_txt, 4 bpp), sized and
placed like LVGL's Montserrat symbols so they mix with them. Montserrat
is set as their fallback (libchumby), so a label in an icon font shows
LV_SYMBOL_* too.

The glyphs go at private codepoints from U+E900 (chumby.h's
CHUMBY_ICON_*), clear of LVGL's symbols (U+F000...).

Run by hand; the output is committed (the build has no PIL):
    icons2lvgl.py MaterialIcons-Regular.ttf  (writes chumby_icons_*.c)
"""
import sys

from PIL import Image, ImageDraw, ImageFont

# (Material codepoint, ours, name)
ICONS = [
    (0xE03E, 0xE900, "radio"),
    (0xE8B5, 0xE901, "clock (schedule)"),
    (0xE894, 0xE902, "globe (language)"),
    (0xE518, 0xE903, "sun (light_mode)"),
    (0xF048, 0xE904, "podcast (podcasts)"),
    (0xE059, 0xE905, "back 10 s (replay_10)"),
    (0xE057, 0xE906, "ahead 30 s (forward_30)"),
]

# Sizes like Montserrat's: (name, glyph px, line_height, base_line)
SIZES = [
    ("chumby_icons_14", 15, 16, 3),
    ("chumby_icons_20", 20, 22, 4),
    ("chumby_icons_28", 28, 30, 5),
]


def render(font, cp):
    """The glyph's coverage, cropped: (w, h, rows of 0..255)."""
    ch = chr(cp)
    l, t, r, b = font.getbbox(ch)
    img = Image.new("L", (r - l, b - t), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
    w, h = img.size
    return w, h, [[img.getpixel((x, y)) for x in range(w)] for y in range(h)]


def pack4(rows):
    """LVGL 4 bpp: all rows back to back, two pixels a byte, high nibble first."""
    px = [v >> 4 for row in rows for v in row]
    if len(px) % 2:
        px.append(0)
    return [(px[i] << 4) | px[i + 1] for i in range(0, len(px), 2)]


def make(ttf, name, size, line_h, base):
    font = ImageFont.truetype(ttf, size)
    bitmap, dscs = [], []
    for src, dst, label in ICONS:
        w, h, rows = render(font, src)
        # Centred on the line's text centre above the baseline, like the
        # Montserrat symbols.
        centre = line_h / 2 - base
        ofs_y = round(centre - h / 2)
        dscs.append((len(bitmap), (w + 2) * 16, w, h, 1, ofs_y, dst, label))
        bitmap.extend(pack4(rows))

    o = ["/* Generated by icons2lvgl.py from Material Icons (Apache-2.0). Do not edit. */",
         '#include "lvgl/lvgl.h"\n', "static const uint8_t glyph_bitmap[] = {"]
    for i in range(0, len(bitmap), 16):
        o.append("    " + ", ".join("0x%02x" % v for v in bitmap[i:i + 16]) + ",")
    o.append("};\n")
    o.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    o.append("    {0},  /* id 0: reserved */")
    for idx, adv, w, h, x, y, dst, label in dscs:
        o.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, "
                 ".ofs_x = %d, .ofs_y = %d},  /* U+%04X %s */" % (idx, adv, w, h, x, y, dst, label))
    o.append("};\n")
    first = ICONS[0][1]
    o.append("""static const lv_font_fmt_txt_cmap_t cmaps[] = {
    {
        .range_start = 0x%X, .range_length = %d, .glyph_id_start = 1,
        .unicode_list = NULL, .glyph_id_ofs_list = NULL,
        .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY
    }
};

static const lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .cmap_num = 1,
    .bpp = 4,
};

lv_font_t %s = {  /* not const: libchumby sets .fallback */
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = %d,
    .base_line = %d,
    .subpx = LV_FONT_SUBPX_NONE,
    .static_bitmap = 1,
    .dsc = &font_dsc,
};""" % (first, len(ICONS), name, line_h, base))
    return "\n".join(o) + "\n"


def main():
    ttf = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else "."
    for name, size, line_h, base in SIZES:
        with open("%s/%s.c" % (out, name), "w") as f:
            f.write(make(ttf, name, size, line_h, base))


if __name__ == "__main__":
    main()
