"""
Convert a BDF bitmap font to an LVGL 9 font (lv_font_fmt_txt, 1 bpp).

    bdf2lvgl.py FONT.bdf NAME [SCALE] > NAME.c

SCALE (default 1) enlarges every glyph by an integer factor with
nearest-neighbour pixels, so a pixel font stays crisp at twice or three
times its size. The line box is padded so the capitals sit exactly in its
middle. The result defines `lv_font_t NAME`.
"""

import sys


def parse_bdf(path):
    props, glyphs = {}, []
    with open(path, encoding="latin-1") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        key, _, rest = line.partition(" ")
        if key in ("FONT_ASCENT", "FONT_DESCENT"):
            props[key] = int(rest)
        elif key == "FONTBOUNDINGBOX":
            props[key] = [int(v) for v in rest.split()]
        elif key == "STARTCHAR":
            g = {"name": rest}
            for line in lines:
                key, _, rest = line.partition(" ")
                if key == "ENCODING":
                    g["cp"] = int(rest.split()[0])
                elif key == "DWIDTH":
                    g["adv"] = int(rest.split()[0])
                elif key == "BBX":
                    g["w"], g["h"], g["x"], g["y"] = (int(v) for v in rest.split())
                elif key == "BITMAP":
                    rows = []
                    for line in lines:
                        if line == "ENDCHAR":
                            break
                        rows.append(int(line, 16) if line else 0)
                    g["rows"] = rows
                    break
            # Rockbox fonts carry a box glyph at 0; LVGL has no use for it.
            if g.get("cp", -1) > 0 and "rows" in g:
                glyphs.append(g)
    if "FONT_ASCENT" not in props:
        bb = props["FONTBOUNDINGBOX"]
        props["FONT_ASCENT"] = bb[1] + bb[3]
        props["FONT_DESCENT"] = -bb[3]
    glyphs.sort(key=lambda g: g["cp"])
    return props, glyphs


def glyph_pixels(g, scale):
    """Rows of 0/1 pixels, scaled."""
    w, h = g["w"], g["h"]
    nbytes = (w + 7) // 8
    out = []
    for r in g["rows"][:h]:
        bits = [(r >> (nbytes * 8 - 1 - i)) & 1 for i in range(w)]
        row = [b for b in bits for _ in range(scale)]
        out.extend([row] * scale)
    return out


def pack(pixels):
    """LVGL 1 bpp: all rows back to back, MSB first, no row padding."""
    bits = [b for row in pixels for b in row]
    out = []
    for i in range(0, len(bits), 8):
        chunk = bits[i:i + 8] + [0] * (8 - len(bits[i:i + 8]))
        out.append(sum(b << (7 - j) for j, b in enumerate(chunk)))
    return out


def main():
    path, name = sys.argv[1], sys.argv[2]
    scale = int(sys.argv[3]) if len(sys.argv) > 3 else 1
    props, glyphs = parse_bdf(path)
    ascent = props["FONT_ASCENT"] * scale
    descent = props["FONT_DESCENT"] * scale

    # Balance the line box on the capitals: equal room above "H" and below
    # the baseline, so centring a label's box centres its text visually.
    cap = next(g for g in glyphs if g["cp"] == ord("H"))
    above = ascent - (cap["y"] + cap["h"]) * scale
    if above < descent:
        ascent += descent - above
    else:
        descent += above - descent

    bitmap, dscs = [], []
    for g in glyphs:
        data = pack(glyph_pixels(g, scale)) if g["w"] and g["h"] else []
        dscs.append((len(bitmap), g["adv"] * scale * 16, g["w"] * scale,
                     g["h"] * scale, g["x"] * scale, g["y"] * scale, g))
        bitmap.extend(data)

    first = glyphs[0]["cp"]
    o = []
    o.append("/* Generated by bdf2lvgl.py from %s, scale %d. Do not edit. */"
             % (path.rsplit("/", 1)[-1], scale))
    o.append('#include "lvgl/lvgl.h"\n')
    o.append("static const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        o.append("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 16]) + ",")
    if not bitmap:
        o.append("    0x00,")
    o.append("};\n")
    o.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    o.append("    {0},  /* id 0: reserved */")
    for idx, adv, w, h, x, y, g in dscs:
        o.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, "
                 ".ofs_x = %d, .ofs_y = %d},  /* U+%04X */"
                 % (idx, adv, w, h, x, y, g["cp"]))
    o.append("};\n")
    o.append("static const uint16_t unicode_list[] = {")
    cps = [g["cp"] - first for g in glyphs]
    for i in range(0, len(cps), 12):
        o.append("    " + ", ".join("%d" % c for c in cps[i:i + 12]) + ",")
    o.append("};\n")
    o.append("""static const lv_font_fmt_txt_cmap_t cmaps[] = {
    {
        .range_start = %d, .range_length = %d, .glyph_id_start = 1,
        .unicode_list = unicode_list, .glyph_id_ofs_list = NULL,
        .list_length = %d, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
    }
};

static const lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .cmap_num = 1,
    .bpp = 1,
};

lv_font_t %s = {  /* not const: liboctopus sets .fallback */
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = %d,
    .base_line = %d,
    .subpx = LV_FONT_SUBPX_NONE,
    .static_bitmap = 1,
    .dsc = &font_dsc,
};""" % (first, cps[-1] + 1, len(cps), name, ascent + descent, descent))
    print("\n".join(o))


if __name__ == "__main__":
    main()
